// 팬싸 레이더 봇 프로필: 동그란 레이더 접시 친구 (32x32 → 512x512)
pal({
  k: "#2a2140",   // 잉크(외곽선·눈)
  w: "#fbf7ee",   // 접시 밝은 면
  s: "#ddd3e6",   // 접시 그늘
  S: "#b3a6c6",   // 접시 깊은 그늘
  r: "#ff7b93",   // 안테나 공 / 볼터치
  R: "#d94f72",
  p: "#ffc4cf",   // 공 하이라이트
  g: "#3fbf6a",   // 신호(응모 중 초록)
  l: "#9fe3a4",   // 연한 신호
  b: "#e3f7d6",   // 배경
  B: "#cdeec0",   // 배경 레이더 고리
})
ramps("kSsw", "kRrp")

sprite("buddy", { w: 32, h: 32, outline: "k" },
  // 접시 몸통
  circ(16, 19, 8, "w"),
  (c) => c.clip((x, y) => (x - 13) * (x - 13) + (y - 16) * (y - 16) > 64, () => c.circ(16, 19, 8, "s")),
  (c) => c.clip((x, y) => (x - 9) * (x - 9) + (y - 11) * (y - 11) > 330, () => c.circ(16, 19, 8, "S")),
  // 다리
  rect(12, 27, 2, 2, "s"), rect(18, 27, 2, 2, "s"),
  // 안테나
  vline(16, 9, 2, "k"),
  circ(16, 7, 1, "r"), px(15, 6, "p"),
  // 얼굴
  rect(13, 18, 1, 2, "k"), rect(19, 18, 1, 2, "k"),
  px(12, 21, "r"), px(13, 21, "r"), px(19, 21, "r"), px(20, 21, "r"),
  px(15, 21, "k"), px(17, 21, "k"), px(16, 22, "k"),
)

scene("avatar", { w: 32, h: 32, bg: "b" },
  layer("rings", ring(16, 16, 14, "B"), ring(16, 16, 11, "B")),
  layer("buddy", stamp("buddy", 0, -2)),
  layer("signal", (c) => {
    // (( • )) 전파: 왼쪽을 찍고 좌우 대칭
    const L = [[12, 6, "g"], [11, 7, "g"], [12, 8, "g"], [9, 5, "l"], [8, 6, "l"], [8, 7, "l"], [8, 8, "l"], [9, 9, "l"]]
    for (const [x, y, k] of L) { c.px(x, y - 2, k); c.px(32 - x, y - 2, k) }
  }),
)
